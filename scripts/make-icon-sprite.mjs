// Generates components/ui/icon-sprite-data.ts from lucide-react's icon nodes for every IconName.
// The data is only imported by the server-rendered <IconSprite/>, so icon paths never ship as JS.
// Re-run after editing components/ui/icon-files.ts:  node scripts/make-icon-sprite.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const src = readFileSync("components/ui/icon-files.ts", "utf8");
const entries = [...src.matchAll(/"([\w-]+)": "([\w-]+)"/g)].map((m) => [m[1], m[2]]);
const out = {};
for (const [name, file] of entries) {
  // Some lucide files are aliases that re-export another icon (e.g. triangle-alert).
  const path = `node_modules/lucide-react/dist/esm/icons/${file}.mjs`;
  const target = readFileSync(path, "utf8").match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/)?.[1] ?? file;
  const mod = await import(pathToFileURL(`node_modules/lucide-react/dist/esm/icons/${target}.mjs`).href);
  // eslint-disable-next-line @typescript-eslint/no-unused-vars -- drop React keys
  out[name] = mod.__iconData.node.map(([tag, { key, ...attrs }]) => [tag, attrs]);
}
writeFileSync(
  "components/ui/icon-sprite-data.ts",
  `// GENERATED by scripts/make-icon-sprite.mjs from lucide-react (ISC) — do not edit.\nexport const ICON_NODES: Record<string, [string, Record<string, string | number>][]> = ${JSON.stringify(out)};\n`,
);
console.log(`${entries.length} icons`);
